<script>
const pfobData = {
    restUrl: '<?php echo rest_url( 'projectfob/v1' ); ?>',
    nonce: '<?php echo wp_create_nonce( 'wp_rest' ); ?>',
    currentMonth: <?php echo $current_month; ?>,
    currentYear: <?php echo $current_year; ?>,
    events: <?php echo json_encode( $all_events ); ?>
};

function renderCalendar() {
    const firstDay = new Date(pfobData.currentYear, pfobData.currentMonth - 1, 1);
    const lastDay = new Date(pfobData.currentYear, pfobData.currentMonth, 0);
    const daysInMonth = lastDay.getDate();
    const startDay = firstDay.getDay();

    let html = '<div class="pfob-calendar-header">';
    ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'].forEach(day => {
        html += `<div class="pfob-calendar-day-name">${day}</div>`;
    });
    html += '</div><div class="pfob-calendar-days">';

    for (let i = 0; i < startDay; i++) {
        html += '<div class="pfob-calendar-cell pfob-empty"></div>';
    }

    for (let day = 1; day <= daysInMonth; day++) {
        const dateStr = `${pfobData.currentYear}-${String(pfobData.currentMonth).padStart(2, '0')}-${String(day).padStart(2, '0')}`;
        const dayEvents = pfobData.events.filter(e => e.start_datetime.startsWith(dateStr));

        html += `<div class="pfob-calendar-cell" data-date="${dateStr}">
            <div class="pfob-day-number">${day}</div>
            <div class="pfob-day-events">`;

        dayEvents.forEach(event => {
            html += `<div class="pfob-event-dot" title="${event.title} (${event.project_name})"></div>`;
        });

        html += '</div></div>';
    }

    html += '</div>';
    document.getElementById('calendar-grid').innerHTML = html;
}

document.getElementById('prev-month').addEventListener('click', () => {
    pfobData.currentMonth--;
    if (pfobData.currentMonth < 1) {
        pfobData.currentMonth = 12;
        pfobData.currentYear--;
    }
    window.location.href = `?month=${pfobData.currentMonth}&year=${pfobData.currentYear}`;
});

document.getElementById('next-month').addEventListener('click', () => {
    pfobData.currentMonth++;
    if (pfobData.currentMonth > 12) {
        pfobData.currentMonth = 1;
        pfobData.currentYear++;
    }
    window.location.href = `?month=${pfobData.currentMonth}&year=${pfobData.currentYear}`;
});

renderCalendar();
</script>
