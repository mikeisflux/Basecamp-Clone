                                <span class="pfob-event-project">
                                    <a href="<?php echo home_url( '/projectfob/projects/' . $event->project_slug . '/schedule/' ); ?>">
                                        <?php echo esc_html( $event->project_name ); ?>
                                    </a>
                                </span>
                                <?php if ( $event->location ) : ?>
                                    <span class="pfob-event-location">📍 <?php echo esc_html( $event->location ); ?></span>
                                <?php endif; ?>
                                <span class="pfob-event-time">
                                    <?php echo date( 'g:i a', strtotime( $event->start_datetime ) ); ?>
                                </span>
                            </div>
                        </div>
                    <?php endforeach; ?>
                <?php endif; ?>
            </div>
        </div>

        <?php if ( ! empty( $user_projects ) ) : ?>
