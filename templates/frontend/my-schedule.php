PFOB_Template::header( 'My Schedule' );

$user_id = get_current_user_id();
$current_month = isset( $_GET['month'] ) ? intval( $_GET['month'] ) : date( 'n' );
$current_year = isset( $_GET['year'] ) ? intval( $_GET['year'] ) : date( 'Y' );

// Get all projects user is a member of
$user_projects = PFOB_Project::get_user_projects( $user_id );
$all_events = array();

// Collect events from all projects
$start_date = "$current_year-$current_month-01";
$end_date = date( 'Y-m-t', strtotime( $start_date ) );

foreach ( $user_projects as $project ) {
    $project_events = PFOB_Event::get_project_events( $project->id, $start_date, $end_date );
    foreach ( $project_events as $event ) {
        $event->project_name = $project->name;
        $event->project_slug = $project->slug;
        $all_events[] = $event;
    }
}

// Get upcoming events across all projects
$upcoming_events = array();
foreach ( $user_projects as $project ) {
    $project_upcoming = PFOB_Event::get_upcoming_events( $project->id, 5 );
    foreach ( $project_upcoming as $event ) {
        $event->project_name = $project->name;
        $event->project_slug = $project->slug;
        $upcoming_events[] = $event;
    }
}

// Sort upcoming events by date
usort( $upcoming_events, function( $a, $b ) {
    return strtotime( $a->start_datetime ) - strtotime( $b->start_datetime );
} );
$upcoming_events = array_slice( $upcoming_events, 0, 10 );
?>

