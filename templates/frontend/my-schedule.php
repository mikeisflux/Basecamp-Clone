            <button id="next-month">&rarr;</button>
        </div>

        <div class="pfob-calendar" id="calendar-grid">
            <!-- Calendar will be generated by JavaScript -->
        </div>

        <div class="pfob-upcoming-events">
            <h3>Upcoming Events</h3>
            <div id="upcoming-events-list">
                <?php if ( empty( $upcoming_events ) ) : ?>
                    <p class="pfob-empty-text">No upcoming events</p>
                <?php else : ?>
                    <?php foreach ( $upcoming_events as $event ) : ?>
                        <div class="pfob-event-item">
                            <div class="pfob-event-date">
                                <?php echo date( 'M j', strtotime( $event->start_datetime ) ); ?>
                            </div>
